// Included after the region fixture helpers in port_regressions.cpp.
static void checkDimensionDiscovery()
{
    char temp[] = "/tmp/mineways-dimensions-XXXXXX";
    assert(mkdtemp(temp));
    std::filesystem::path root(temp);
    writeWorldFixture(root, "minecraft:stone");
    writeWorldFixture(root / "dimensions" / "example" / "moon", "minecraft:gold_block");
    writeWorldFixture(root / "dimensions" / "example" / "nested" / "cave", "minecraft:dirt");
    writeWorldFixture(root / "dimensions" / "minecraft" / "the_nether", "minecraft:netherrack");
    writeWorldFixture(root / "dimensions" / "example" / "moon" / "underground", "minecraft:dirt");
    std::filesystem::create_directory_symlink(root / "dimensions", root / "dimensions" / "loop");
    writeWorldFixture(root / "dimensions" / "example" / "bad:colon", "minecraft:dirt");
    writeWorldFixture(root / "dimensions" / "example" / "bad\nheader", "minecraft:dirt");
    writeWorldFixture(root / "dimensions" / "Uppercase_namespace" / "uppercase", "minecraft:dirt");
    writeWorldFixture(root / "dimensions" / "empty_namespace_id", "minecraft:dirt");
    WorldGuide guide = fixtureGuide(root);
    guide.newFormat = true;
    SetDimensionDirectory(&guide, 0);
    assert(std::wstring(guide.directory) == std::wstring(guide.world) + L"/");
    auto dimensions = DiscoverWorldDimensions(&guide);
    assert(dimensions.size() == 5);
    bool underParent = false;
    for (const auto& dim : dimensions) if (dim.id == L"example:moon/underground") underParent = true;
    assert(underParent);
    bool nested = false;
    for (const auto& dim : dimensions) if (dim.id == L"example:nested/cave") nested = true;
    assert(nested);
    int worldType = LIGHTING;
    assert(SelectWorldDimension(&guide, L"example:moon", &worldType));
    assert(worldType == LIGHTING);
    assert(std::wstring(guide.dimensionId) == L"example:moon");
    SetDimensionDirectory(&guide, HELL); // selected path survives map/export callers
    assert(std::wstring(guide.directory).find(L"example/moon/") != std::wstring::npos);
    int result = 0;
    WorldBlock* block = LoadBlock(&guide, 0, 0, DATA_VERSION_TO_RELEASE_NUMBER(3953), 3953, result);
    assert(block && block->grid[(0 - guide.minHeight) * 256] == BLOCK_OF_GOLD);
    block_free(block);
    WorldGuide previous = guide;
    assert(!SelectWorldDimension(&guide, L"../../outside", &worldType));
    assert(memcmp(&previous, &guide, sizeof(guide)) == 0);
    assert(SelectWorldDimension(&guide, L"minecraft:the_nether", &worldType));
    assert((worldType & HELL) && !(worldType & ENDER));
    assert(guide.minHeight == 0 && guide.maxHeight == 255);
    assert(SelectWorldDimension(&guide, L"minecraft:overworld", &worldType));
    assert(worldType == LIGHTING);
    assert(std::wstring(guide.directory) == std::wstring(guide.world) + L"/");
    block = LoadBlock(&guide, 0, 0, DATA_VERSION_TO_RELEASE_NUMBER(3953), 3953, result);
    assert(block && block->grid[(0 - guide.minHeight) * 256] == BLOCK_STONE);
    block_free(block);
    const auto metadataPath = root / "dimensions.mwpack";
    FILE* metadata = fopen(metadataPath.c_str(), "wb");
    assert(metadata);
    fputs("MINEWAYS_MOD_PACK\t1\ndimension\texample:moon\t-128\t512\t3\n"
          "dimension\texample:missing\t0\t256\t2\n", metadata);
    assert(fclose(metadata) == 0);
    std::string error;
    assert(LoadModPack(metadataPath.u8string(), error));
    assert(DiscoverWorldDimensions(&guide).size() == 5);
    assert(SelectWorldDimension(&guide, L"example:moon", &worldType));
    assert(guide.dimensionBoundsFromPack && guide.minHeight == -128 && guide.maxHeight == 383 && guide.dimensionScale == 3);
    int minHeight = 0, maxHeight = 255;
    GetChunkHeights(&guide, minHeight, maxHeight, DATA_VERSION_TO_RELEASE_NUMBER(3953), 0, 0);
    assert(minHeight == -128 && maxHeight == 383);
    assert(WorldDimensionScale(&guide, worldType) == 3);
    assert(ConvertDimensionCoordinate(24, 3, 8) == 9);
    assert(ConvertDimensionCoordinate(9, 8, 3) == 24);
    assert(ConvertDimensionCoordinate(30000000, 1e6, 1e-6) == 30000000);
    assert(DimensionCoordinateScale("minecraft:the_nether") == 8);
    ClearModPack();
    assert(SelectWorldDimension(&guide, L"example:moon", &worldType));
    assert(!guide.dimensionBoundsFromPack && guide.dimensionScale == 1);
    ClearLoadedWorldData();
    assert(gWorldGuide.dimensionId[0] == 0 && gWorldGuide.dimensionPath[0] == 0);
    ImportedSet settings;
    settings.readingModel = false;
    settings.processData = false;
    char valid[] = "Dimension: example:nested/cave";
    assert(InterpretImportLine(valid, settings) & INTERPRETER_FOUND_VALID_LINE);
    char missing[] = "Dimension:";
    assert(InterpretImportLine(missing, settings) == INTERPRETER_FOUND_ERROR);
    char pack[] = "Mod pack: /tmp/example.mwpack";
    assert(InterpretImportLine(pack, settings) & INTERPRETER_FOUND_VALID_LINE);
    char clear[] = "Clear mod pack";
    assert(InterpretImportLine(clear, settings) & INTERPRETER_FOUND_VALID_LINE);
    char invalidId[] = "Dimension: example:../outside";
    assert(InterpretImportLine(invalidId, settings) == INTERPRETER_FOUND_ERROR);
    char invalidClear[] = "Clear mod pack extra";
    assert(InterpretImportLine(invalidClear, settings) == INTERPRETER_FOUND_ERROR);
    assert(!IsWorldDimensionId("missing_namespace"));
    assert(!IsWorldDimensionId("example:path\nheader"));
    CloseAll();
    block_pool_trim();
    std::filesystem::remove_all(root);
}
